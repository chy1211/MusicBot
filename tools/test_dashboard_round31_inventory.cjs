#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),path=require("node:path");
const root=path.resolve(__dirname,".."),dir=path.join(root,"tests");
const ts=require(require.resolve("typescript",{paths:[path.join(root,"frontend")]}));
let md="# Current dashboard Node test inventory\n\nGenerated by `node tools/test_dashboard_round31_inventory.cjs`. Legacy global-script tests were removed in round 41; current rendered UI behavior is exercised by `tools/test_dashboard_round31.cjs` and `tools/test_dashboard_touch.cjs`. This is a source inventory, not a claim of runtime pass counts or one-to-one coverage.\n";
for(const name of fs.readdirSync(dir).filter(n=>/^test_.*\.cjs$/.test(n)).sort()){
 const source=ts.createSourceFile(name,fs.readFileSync(path.join(dir,name),"utf8"),ts.ScriptTarget.Latest,true);
 const titles=[];function walk(node){if(ts.isCallExpression(node)&&ts.isIdentifier(node.expression)&&node.expression.text==='test'&&ts.isStringLiteral(node.arguments[0]))titles.push(node.arguments[0].text);ts.forEachChild(node,walk)}walk(source);
 md+='\n## `'+name+'`\n\n'+titles.map(t=>'- '+t).join('\n')+'\n';
}
fs.writeFileSync(path.join(root,"frontend/TEST-MIGRATION.md"),md);
console.log('Updated current dashboard test inventory');
